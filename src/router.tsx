import { createRouter } from "@tanstack/react-router";

import { routeTree } from "./routeTree.gen";

/**
 * The router factory, one per server render and one per browser session.
 *
 * ---------------------------------------------------------------------------
 * WHY A FACTORY AND NOT A MODULE CONSTANT
 * ---------------------------------------------------------------------------
 * The previous framework let `app/providers.tsx` own the cache with a
 * `useState` initializer, so a fresh `QueryClient` per mount was the rule. That
 * rule survives the migration unchanged and simply moves here: a router built
 * at module scope is shared by every request a server process serves, which is
 * how one visitor's pathname leaks into another visitor's screen.
 *
 * ---------------------------------------------------------------------------
 * WHY `routeTree.gen` IS COMMITTED
 * ---------------------------------------------------------------------------
 * It is generated by `@tanstack/router-plugin` during `vite dev` and
 * `npm run build`, and it is committed on purpose. CI typechecks BEFORE it
 * builds (`rm -rf .output && npm run typecheck` then `npm run build`), and
 * `npm run typecheck` is `tsc --noEmit` — so on a fresh clone the import below
 * has to resolve before any plugin has run. This repository's rule is that
 * typecheck works on a clean checkout, exactly when you most want it to, and a
 * typecheck that needs a prior build is a typecheck nobody has run.
 *
 * The consequence is a generated file in git, and the cost is that a route
 * added without a build is invisible to `tsc`. `src/router.test.tsx` is the
 * guard: it imports this module and asserts every file under `src/routes/`
 * appears in the committed tree, so a stale tree is a red `npm test` and not a
 * type error that only appears after somebody else runs a build.
 */
/**
 * A router, per server render and per browser session.
 *
 * `options` exists for the render harness, which needs a memory history so a
 * test's navigation does not touch `window.history` — see
 * `src/test/support/render.tsx`. It is typed from the library's own options
 * rather than from `@tanstack/history`, so nothing here depends on a package
 * this repository does not declare.
 */
export function getRouter(options: Omit<Parameters<typeof createRouter>[0], "routeTree"> = {}) {
  return createRouter({
    scrollRestoration: true,
    ...options,
    routeTree,
  });
}

declare module "@tanstack/react-router" {
  interface Register {
    router: ReturnType<typeof getRouter>;
  }
}